"""Version rules: what this tools release supports versus what the project pins.

Since the split (decision-35) the tools import a runtime they were tested
against - the range ``qgis-sdk-tools`` declares on ``qgis-sdk-runtime`` - and
generate clients for one contract version. A project that pins a runtime
outside that range, or carries a client generated for another contract
version, will not behave the way this ``qgis-sdk`` release expects; ``check``
says so instead of letting ``dev`` or ``build`` find out.

Both rules read files only. The supported range comes from the installed
``qgis-sdk-tools`` metadata, or from the checkout's own manifest when the
tools run from source; when neither is readable the rule is skipped, never
guessed.

``VERSION003``/``VERSION004`` (decision-43 amendment) read the project's own
requirement on the runtime: ``build`` vendors the ``qgis_sdk`` this
interpreter imports, so that copy must be one the project declares it works
with. No declaration is a warning and the build uses what is installed;
an installed runtime outside the declared specifier is an error with the
``pip`` line that would fix it - the tools never install.
"""

from __future__ import annotations

import importlib.metadata
import re
from collections.abc import Callable, Iterator
from dataclasses import dataclass
from pathlib import Path

from qgis_sdk.bridge.protocol import HOST_SCHEMA_VERSION
from qgis_sdk.declarations import PLUGIN_DESCRIPTION_SCHEMA_VERSION

from qgis_sdk_tools.check.diagnostics import Diagnostic
from qgis_sdk_tools.manifest import read_pyproject, table
from qgis_sdk_tools.paths import walk_files

TOOLS_DISTRIBUTION = "qgis-sdk-tools"
RUNTIME_DISTRIBUTION = "qgis-sdk-runtime"
RUNTIME_REQUIREMENT_NAMES = frozenset({RUNTIME_DISTRIBUTION, "qgis-sdk"})
GENERATED_MARKER = "// Generated by qgis-sdk. Do not edit."
REQUIREMENT = re.compile(
    r"^\s*(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)\s*(?P<extras>\[[^\]]*\])?\s*(?P<spec>[^;]*?)\s*(?:;.*)?$"
)
CLAUSE = re.compile(r"^(?P<op>===|==|!=|~=|<=|>=|<|>)\s*(?P<version>\S+)$")
_CONTRACT_CONSTANT = re.compile(
    r"^export const (?P<name>PLUGIN_DESCRIPTION_SCHEMA_VERSION|HOST_SCHEMA_VERSION)"
    r"\s*=\s*(?P<value>\d+)\s*;"
)
_CONTRACT_AT_HEAD = {
    "PLUGIN_DESCRIPTION_SCHEMA_VERSION": PLUGIN_DESCRIPTION_SCHEMA_VERSION,
    "HOST_SCHEMA_VERSION": HOST_SCHEMA_VERSION,
}
_NOT_THE_AUTHORS = frozenset(
    {"node_modules", ".git", "dist", "build", ".pixi", ".venv"}
)


@dataclass(frozen=True, slots=True)
class RuntimeRange:
    """``>=lower,<upper``: the runtime versions this tools release was tested with."""

    lower: str
    upper: str

    def as_requirement(self) -> str:
        return f"{RUNTIME_DISTRIBUTION}>={self.lower},<{self.upper}"


def supported_runtime_range() -> RuntimeRange | None:
    """The tools' declared runtime range, from metadata or the source manifest."""
    requirements: list[str] = []
    try:
        requirements = list(importlib.metadata.requires(TOOLS_DISTRIBUTION) or ())
    except importlib.metadata.PackageNotFoundError:
        source = Path(__file__).resolve().parents[4] / "pyproject.toml"
        data, _malformed = read_pyproject(source)
        project = table(data, "project") or {}
        if project.get("name") == TOOLS_DISTRIBUTION:
            requirements = [str(r) for r in project.get("dependencies", [])]
    for requirement in requirements:
        found = _runtime_range_of(requirement)
        if found is not None:
            return found
    return None


def _runtime_range_of(requirement: str) -> RuntimeRange | None:
    """``>=X,<Y`` on the runtime, in either clause order (metadata normalizes it)."""
    match = REQUIREMENT.match(requirement)
    if match is None or match.group("name").lower() != RUNTIME_DISTRIBUTION:
        return None
    lower = upper = None
    for raw in match.group("spec").split(","):
        clause = CLAUSE.match(raw.strip())
        if clause is None:
            continue
        if clause.group("op") == ">=":
            lower = clause.group("version")
        elif clause.group("op") == "<":
            upper = clause.group("version")
    if lower is None or upper is None:
        return None
    return RuntimeRange(lower, upper)


def release(text: str) -> tuple[int, ...]:
    digits = re.match(r"\d+(?:\.\d+)*", text.strip())
    if digits is None:
        raise ValueError(text)
    return tuple(int(part) for part in digits.group(0).split("."))


def _pad(
    a: tuple[int, ...], b: tuple[int, ...]
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    width = max(len(a), len(b))
    return a + (0,) * (width - len(a)), b + (0,) * (width - len(b))


def lt(a: tuple[int, ...], b: tuple[int, ...]) -> bool:
    a, b = _pad(a, b)
    return a < b


def eq(a: tuple[int, ...], b: tuple[int, ...]) -> bool:
    a, b = _pad(a, b)
    return a == b


Bound = tuple[tuple[int, ...], bool]  # (version, inclusive)


def _tighter_lower(current: Bound | None, candidate: Bound) -> Bound:
    if current is None or lt(current[0], candidate[0]):
        return candidate
    if eq(current[0], candidate[0]) and current[1] and not candidate[1]:
        return candidate
    return current


def _tighter_upper(current: Bound | None, candidate: Bound) -> Bound:
    if current is None or lt(candidate[0], current[0]):
        return candidate
    if eq(current[0], candidate[0]) and current[1] and not candidate[1]:
        return candidate
    return current


def _nonempty(lower: Bound | None, upper: Bound | None) -> bool:
    if lower is None or upper is None:
        return True
    if lt(lower[0], upper[0]):
        return True
    return eq(lower[0], upper[0]) and lower[1] and upper[1]


def next_after_prefix(prefix: tuple[int, ...]) -> tuple[int, ...]:
    return (*prefix[:-1], prefix[-1] + 1)


def _exact_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    lower, upper = bounds
    return (
        _tighter_lower(lower, (version, True)),
        _tighter_upper(upper, (version, True)),
    )


def _at_least_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    return _tighter_lower(bounds[0], (version, True)), bounds[1]


def _more_than_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    return _tighter_lower(bounds[0], (version, False)), bounds[1]


def _at_most_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    return bounds[0], _tighter_upper(bounds[1], (version, True))


def _less_than_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    return bounds[0], _tighter_upper(bounds[1], (version, False))


def _compatible_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    lower = _tighter_lower(bounds[0], (version, True))
    if len(version) >= 2:
        upper = _tighter_upper(bounds[1], (next_after_prefix(version[:-1]), False))
        return lower, upper
    return lower, bounds[1]


def _exclude_bounds(bounds: _Bounds, version: tuple[int, ...]) -> _Bounds:
    """``!=`` alone cannot empty a range (see the rule's docstring)."""
    return bounds


_Bounds = tuple[Bound | None, Bound | None]
_RANGE_CLAUSES: dict[str, Callable[[_Bounds, tuple[int, ...]], _Bounds]] = {
    "==": _exact_bounds,
    "===": _exact_bounds,
    ">=": _at_least_bounds,
    ">": _more_than_bounds,
    "<=": _at_most_bounds,
    "<": _less_than_bounds,
    "~=": _compatible_bounds,
    "!=": _exclude_bounds,
}


def _range_bounds(specifier: str, supported: RuntimeRange) -> _Bounds | None:
    """Tighten the supported range clause by clause; ``None`` means admitting."""
    bounds: _Bounds = (
        (release(supported.lower), True),
        (release(supported.upper), False),
    )
    for raw in specifier.split(","):
        clause = raw.strip()
        if not clause:
            continue
        match = CLAUSE.match(clause)
        if match is None:
            return None
        op, text = match.group("op"), match.group("version")
        try:
            if op in ("==", "===") and text.endswith(".*"):
                prefix = release(text[:-2])
                bounds = (
                    _tighter_lower(bounds[0], (prefix, True)),
                    _tighter_upper(bounds[1], (next_after_prefix(prefix), False)),
                )
                continue
            version = release(text)
        except ValueError:
            return None
        tighten = _RANGE_CLAUSES.get(op)
        if tighten is None:
            return None
        bounds = tighten(bounds, version)
    return bounds


def requirement_admits_range(specifier: str, supported: RuntimeRange) -> bool:
    """Whether some version in ``supported`` satisfies ``specifier``.

    ``!=`` clauses are ignored: on their own they cannot empty a range. An
    unparsable clause makes the specifier count as admitting, so a syntax the
    arithmetic does not know is never reported as a mismatch.
    """
    bounds = _range_bounds(specifier, supported)
    if bounds is None:
        return True
    return _nonempty(*bounds)


def requirement_strings(data: object) -> Iterator[str]:
    """Every requirement string a pyproject can declare, wherever it declares it."""
    if not isinstance(data, dict):
        return
    project = data.get("project")
    if isinstance(project, dict):
        yield from (r for r in project.get("dependencies", ()) if isinstance(r, str))
        extras = project.get("optional-dependencies")
        if isinstance(extras, dict):
            for listed in extras.values():
                if isinstance(listed, list):
                    yield from (r for r in listed if isinstance(r, str))
    groups = data.get("dependency-groups")
    if isinstance(groups, dict):
        for listed in groups.values():
            if isinstance(listed, list):
                # ``{include-group = ...}`` entries are tables, not requirements.
                yield from (r for r in listed if isinstance(r, str))


def _runtime_pin_finding(requirement: str, supported: RuntimeRange) -> Diagnostic:
    """VERSION001: one requirement that cannot meet the supported range."""
    shown = requirement.split(";", 1)[0].strip()
    return Diagnostic(
        rule="VERSION001",
        path=Path("pyproject.toml"),
        line=0,
        column=0,
        message=(
            f"pins `{shown}`, outside the runtime range this {TOOLS_DISTRIBUTION} "
            f"release supports (>={supported.lower},<{supported.upper})"
        ),
        remediation=(
            f"Move the pin into the range (`{supported.as_requirement()}`), "
            f"or install the {TOOLS_DISTRIBUTION} release that was tested "
            "with the runtime you pin."
        ),
    )


def check_runtime_pins(root: Path) -> Iterator[Diagnostic]:
    """Report every runtime (or kit) requirement that cannot meet the supported range."""
    data, _malformed = read_pyproject(root / "pyproject.toml")
    if data is None:
        return  # absent, or CONFIG001 already reports an unparsable manifest.
    supported = supported_runtime_range()
    if supported is None:
        return
    for requirement in requirement_strings(data):
        match = REQUIREMENT.match(requirement)
        if match is None:
            continue
        name = match.group("name").lower().replace("_", "-")
        if name not in RUNTIME_REQUIREMENT_NAMES:
            continue
        if requirement_admits_range(match.group("spec"), supported):
            continue
        yield _runtime_pin_finding(requirement, supported)


def _generated_typescript(root: Path) -> Iterator[Path]:
    for path in walk_files(root, skip=_NOT_THE_AUTHORS, suffix=".ts"):
        try:
            with path.open(encoding="utf-8") as handle:
                first = handle.readline().rstrip("\n")
        except OSError:
            continue
        if first == GENERATED_MARKER:
            yield path


def check_generated_clients(root: Path) -> Iterator[Diagnostic]:
    """Report a generated client whose contract constants are not this release's."""
    for path in _generated_typescript(root):
        relative = path.relative_to(root)
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = _CONTRACT_CONSTANT.match(line)
            if match is None:
                continue
            name, found = match.group("name"), int(match.group("value"))
            expected = _CONTRACT_AT_HEAD[name]
            if found == expected:
                continue
            surface = "description" if name.startswith("PLUGIN") else "host"
            yield Diagnostic(
                rule="VERSION002",
                path=relative,
                line=number,
                column=1,
                message=(
                    f"generated client declares {surface} schema version {found}; "
                    f"this qgis-sdk release generates version {expected}"
                ),
                remediation=(
                    "Regenerate it with `qgis-sdk bridge generate` from this "
                    "release, or install the release that generated it."
                ),
            )


RUNTIME_DISTRIBUTIONS = (RUNTIME_DISTRIBUTION, "qgis-sdk")


def installed_runtime_version() -> str | None:
    """The version of the ``qgis_sdk`` this interpreter imports, or ``None``.

    Distribution metadata first; from a source checkout, the runtime
    package's own manifest. ``None`` when neither says.
    """
    for name in RUNTIME_DISTRIBUTIONS:
        try:
            return importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            continue
    try:
        import qgis_sdk
    except ImportError:  # pragma: no cover - the tools depend on the runtime
        return None
    manifest = Path(qgis_sdk.__file__).resolve().parents[2] / "pyproject.toml"
    try:
        data, _malformed = read_pyproject(manifest)
    except OSError:
        return None
    project = table(data, "project")
    if project is None or project.get("name") != RUNTIME_DISTRIBUTION:
        return None
    version = project.get("version")
    return version if isinstance(version, str) else None

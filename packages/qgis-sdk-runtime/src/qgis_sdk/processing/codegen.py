_RESERVED_FIELDS = frozenset({"algorithm", "params", "to_run"})
_NON_WORD = re.compile(r"[^0-9A-Za-z]+")


def python_type(parameter: ParameterInfo) -> str:
    """The annotation of one parameter in the generated Python."""
    if parameter.multiple and parameter.kind in _PYTHON_LIST_KINDS:
        return _PYTHON_LIST_KINDS[parameter.kind]
    return PYTHON_TYPES.get(parameter.kind, "object")


def typescript_type(parameter: ParameterInfo) -> str:
    """The type of one parameter in the generated TypeScript."""
    if parameter.multiple and parameter.kind in _TYPESCRIPT_LIST_KINDS:
        return _TYPESCRIPT_LIST_KINDS[parameter.kind]
    return TYPESCRIPT_TYPES.get(parameter.kind, "unknown")


def field_name(name: str, taken: Iterable[str] = ()) -> str:
    """The Python field for a QGIS parameter name: ``END_CAP_STYLE`` -> ``end_cap_style``.

    A GRASS flag (``-c``) becomes ``flag_c``; names that would clash with a
    keyword, a ``TypedRun`` member or an earlier field get a trailing
    underscore.
    """
    flag = name.startswith("-")
    base = _NON_WORD.sub("_", name).strip("_").lower() or "parameter"
    if flag:
        base = f"flag_{base}"
    if base[0].isdigit():
        base = f"p_{base}"
    if keyword.iskeyword(base) or base in _RESERVED_FIELDS or base.startswith("_"):
        base = f"{base}_"
    taken_set = set(taken)
    candidate = base
    while candidate in taken_set:
        candidate = f"{candidate}_"
    return candidate


def class_name(algorithm: AlgorithmInfo, taken: Iterable[str] = ()) -> str:
    """``Basic statistics for fields`` -> ``BasicStatisticsForFields``.

    Built from the label because QGIS names are squashed
    (``basicstatisticsforfields``); a label that collides within a provider
    falls back to the name, then to a numeric suffix.
    """
    taken_set = set(taken)
    for source in (algorithm.label, algorithm.name):
        words = [w for w in _NON_WORD.split(source) if w]
        candidate = "".join(w[:1].upper() + w[1:] for w in words) or "Algorithm"
        if candidate[0].isdigit():
            candidate = f"Algorithm{candidate}"
        if candidate not in taken_set and not keyword.iskeyword(candidate):
            return candidate
    base = candidate
    index = 2
    while f"{base}{index}" in taken_set:
        index += 1
    return f"{base}{index}"


def _q(value: str) -> str:
    """A double-quoted Python literal, as ``ruff format`` would write it."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _docstring(lines: Sequence[str], indent: str) -> str:
    text = "\n".join(lines).replace("\\", "\\\\").replace('"""', "'''")
    body = "\n".join(
        f"{indent}{line.rstrip()}" if line.strip() else "" for line in text.split("\n")
    )
    return f'{indent}"""{body[len(indent) :]}\n{indent}"""'


def _first_sentence(text: str, limit: int = 240) -> str:
    first = text.strip().split("\n", 1)[0].strip()
    return first if len(first) <= limit else first[: limit - 1].rstrip() + "…"


def emit_python_module(
    catalogue: Catalogue, provider: str, *, module_name: str | None = None
) -> str:
    """The Python module for one provider of ``catalogue``."""
    algorithms = catalogue.by_provider(provider)
    body: list[str] = [f"PROVIDER = {_q(provider)}", ""]
    classes: list[tuple[str, str]] = []
    taken: set[str] = set()
    for algorithm in algorithms:
        name = class_name(algorithm, taken)
        taken.add(name)
        classes.append((algorithm.id, name))
        body.extend(_python_algorithm(algorithm, name))
    if not algorithms:
        body.append("")
    body.append("#: Every request class of this provider by algorithm id.")
    body.append("REGISTRY: dict[str, type[TypedRun]] = {")
    body.extend(f"    {_q(algorithm_id)}: {name}," for algorithm_id, name in classes)
    body.append("}")
    body.append("")
    body.append("ALGORITHM_IDS: tuple[str, ...] = tuple(REGISTRY)")
    body.append("")
    exported = ["ALGORITHM_IDS", "PROVIDER", "REGISTRY"]
    exported += sorted(
        {f"{n}{suffix}" for _, n in classes for suffix in ("", "Params", "Result")}
    )
    body.append("__all__ = [")
    body.extend(f'    "{name}",' for name in exported)
    body.extend(["]", ""])
    text = "\n".join(body)

    # Import only what the module uses, so a small provider lints clean.
    def used(names: Sequence[str]) -> list[str]:
        return [n for n in names if re.search(rf"\b{n}\b", text)]

    models = ["FileRef", "TypedRun", "VectorLayerInfo"]
    value_types = ["Destination", "Extent", "LayerRef", "PointValue", "RangeValue"]
    typing = ["ClassVar"] + used(["Required"]) + ["TypedDict"]
    header: list[str] = [
        f'"""{HEADER.format(version=catalogue.qgis_version)}',
        "",
        f"Provider ``{provider}``: {len(algorithms)} algorithms. Each algorithm has a",
        "``...Params`` TypedDict (the QGIS parameter names, for ``run(id, params)``),",
        "a ``...Result`` TypedDict (its output names) and a keyword-only request",
        "class deriving from ``TypedRun`` (``run(native.Buffer(input=...))``).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        f"from typing import {', '.join(typing)}",
        "",
        f"from qgis_sdk.models import {', '.join(used(models))}",
    ]
    if used(value_types):
        header.append(
            f"from qgis_sdk.processing.types import {', '.join(used(value_types))}"
        )
    header.extend(["", ""])
    return "\n".join(header) + text


def _python_algorithm(algorithm: AlgorithmInfo, name: str) -> list[str]:
    lines: list[str] = []
    # Params TypedDict with the QGIS names (functional form: GRASS flags are
    # not identifiers).
    entries: list[str] = []
    for parameter in algorithm.parameters:
        annotation = python_type(parameter)
        if parameter.required:
            annotation = f"Required[{annotation}]"
        entries.append(f"        {_q(parameter.name)}: {annotation},")
    lines.extend(_typed_dict(f"{name}Params", entries))
    lines.extend(
        _typed_dict(
            f"{name}Result",
            [f"        {_q(o.name)}: {_python_output(o)}," for o in algorithm.outputs],
        )
    )
    lines.append("")
    lines.append("")
    lines.append("@dataclass(frozen=True, slots=True, kw_only=True)")
    lines.append(f"class {name}(TypedRun):")
    doc = [f"{algorithm.label} (``{algorithm.id}``)."]
    if algorithm.help:
        doc += ["", _first_sentence(algorithm.help)]
    fields: list[tuple[str, ParameterInfo]] = []
    used: list[str] = []
    for parameter in algorithm.parameters:
        field = field_name(parameter.name, used)
        used.append(field)
        fields.append((field, parameter))
    doc += ["", "Parameters:"]
    for field, parameter in fields:
        note = " (required)" if parameter.required else ""
        if parameter.destination:
            note = " (destination; allocated when left out)"
        label = parameter.label or parameter.name
        doc.append(f"    {field}: {label}{note}")
        if parameter.options:
            doc.append(f"        one of: {', '.join(parameter.options)}")
    if algorithm.outputs:
        doc += ["", "Outputs: " + ", ".join(o.name for o in algorithm.outputs)]
    lines.append(_docstring(doc, "    "))
    lines.append("")
    algorithm_line = f"    algorithm: ClassVar[str] = {_q(algorithm.id)}"
    if len(algorithm_line) > 88:
        algorithm_line = (
            f"    algorithm: ClassVar[str] = (\n        {_q(algorithm.id)}\n    )"
        )
    lines.append(algorithm_line)
    if fields:
        lines.append("    _names: ClassVar[dict[str, str]] = {")
        lines.extend(
            f"        {_q(field)}: {_q(parameter.name)}," for field, parameter in fields
        )
        lines.append("    }")
    else:
        lines.append("    _names: ClassVar[dict[str, str]] = {}")
    required = [(f, p) for f, p in fields if p.required]
    optional = [(f, p) for f, p in fields if not p.required]
    for field, parameter in required:
        lines.append(f"    {field}: {python_type(parameter)}")
    for field, parameter in optional:
        lines.append(f"    {field}: {python_type(parameter)} | None = None")
    lines.append("")
    lines.append("")
    return lines


def _typed_dict(name: str, entries: Sequence[str]) -> list[str]:
    """A functional ``TypedDict`` as ``ruff format`` lays it out."""
    if not entries:
        return [
            f"{name} = TypedDict(",
            f'    "{name}",',
            "    {},",
            "    total=False,",
            ")",
        ]
    return [
        f"{name} = TypedDict(",
        f'    "{name}",',
        "    {",
        *entries,
        "    },",
        "    total=False,",
        ")",
    ]


def _python_output(output: OutputInfo) -> str:
    return PYTHON_OUTPUT_TYPES.get(output.kind, "object")


def emit_python_package_init(catalogue: Catalogue, providers: Sequence[str]) -> str:
    """The ``__init__`` of a generated package: the catalogue and its providers."""
    return "\n".join(
        [
            f'"""{HEADER.format(version=catalogue.qgis_version)}',
            "",
            "The catalogue these modules were generated from is ``catalogue.json``",
            "next to this file; ``CATALOGUE`` loads it once. Import a provider",
            "module (``from <this package> import native``) for its request classes.",
            '"""',
            "",
            "from __future__ import annotations",
            "",
            "from pathlib import Path",
            "",
            "from qgis_sdk.processing.snapshot import load_catalogue",
            "",
            f"QGIS_VERSION = {_q(catalogue.qgis_version)}",
            "PROVIDERS: tuple[str, ...] = ("
            + "".join(f"{_q(p)}, " for p in providers)
            + ")",
            'CATALOGUE = load_catalogue(Path(__file__).with_name("catalogue.json"))',
            "",
            '__all__ = ["CATALOGUE", "PROVIDERS", "QGIS_VERSION"]',
            "",
        ]
    )


def _ts_prefix(provider_id: str) -> str:
    """``native`` -> ``Native``, ``3d`` -> ``P3d``: the per-provider type prefix."""
    provider = "".join(w[:1].upper() + w[1:] for w in _NON_WORD.split(provider_id) if w)
    if provider[:1].isdigit():
        provider = f"P{provider}"
    return provider


def _ts_key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else f'"{name}"'


def emit_typescript_module(
    catalogue: Catalogue,
    providers: Sequence[str] | None = None,
    *,
    package: str = "@archont561/qgis-sdk",
) -> str:
    """One TypeScript module for ``providers`` (default: all in the catalogue)."""
    wanted = (
        tuple(providers)
        if providers is not None
        else tuple(p.id for p in catalogue.providers)
    )
    algorithms = [a for a in catalogue.algorithms if a.provider in wanted]
    out: list[str] = [
        f"// {HEADER.format(version=catalogue.qgis_version)}",
        "// Regenerate with `qgis-sdk processing generate`; CI fails when this file is stale.",
        "",
        "import {",
        "\ttype AlgorithmHost,",
        "\ttype AlgorithmRun,",
        "\ttype Destination,",
        "\ttype Extent,",
        "\ttype FileRef,",
        "\ttype HostInvokeOptions,",
        "\ttype LayerRef,",
        "\ttype PointValue,",
        "\ttype RangeValue,",
        "\trunAlgorithm as runAny,",
        "\ttype VectorLayerInfo,",
        f'}} from "{package}";',
        "",
        f"export const QGIS_VERSION = {_ts_string(catalogue.qgis_version)};",
        f"export const PROVIDERS = [{', '.join(_ts_string(p) for p in wanted)}] as const;",
        "",
    ]
    names: list[tuple[str, str]] = []
    taken: dict[str, set[str]] = {}
    for algorithm in algorithms:
        base = class_name(algorithm, taken.setdefault(algorithm.provider, set()))
        taken[algorithm.provider].add(base)
        name = _ts_prefix(algorithm.provider) + base
        names.append((algorithm.id, name))
        out.append(f"/** {algorithm.label} (`{algorithm.id}`). */")
        out.append(f"export interface {name}Params {{")
        for parameter in algorithm.parameters:
            optional = "" if parameter.required else "?"
            doc = parameter.label or parameter.name
            if parameter.options:
                doc += f" — one of: {', '.join(parameter.options)}"
            out.append(f"\t/** {_ts_comment(doc)} */")
            out.append(
                f"\t{_ts_key(parameter.name)}{optional}: {typescript_type(parameter)};"
            )
        out.append("}")
        out.append(f"export interface {name}Result {{")
        for output in algorithm.outputs:
            out.append(
                f"\t{_ts_key(output.name)}?: "
                f"{TYPESCRIPT_OUTPUT_TYPES.get(output.kind, 'unknown')};"
            )
        out.append("}")
        out.append("")
    out.append(
        "/** Every generated algorithm by id; `runAlgorithm` is generic over it. */"
    )
    out.append("export interface AlgorithmRegistry {")
    for algorithm_id, name in names:
        out.append(
            f'\t"{algorithm_id}": {{ params: {name}Params; result: {name}Result }};'
        )
    out.append("}")
    out.append("")
    out.append("export const ALGORITHM_IDS = [")
    out.extend(f'\t"{algorithm_id}",' for algorithm_id, _ in names)
    out.append("] as const;")
    out.append("")
    out.append("export type AlgorithmId = keyof AlgorithmRegistry;")
    out.append("")
    out.extend(_TS_RUN.splitlines())
    out.append("")
    return "\n".join(out)


#: The bound runner: the bridge's generic ``runAlgorithm`` with this module's
#: registry filled in, so a page writes ``runAlgorithm(qgis, "native:buffer",
#: { INPUT })`` and the parameters and the result are typed by the id.
_TS_RUN = """\
/** Run one algorithm of this registry through `qgis.host.algorithms.run`. */
export function runAlgorithm<K extends AlgorithmId>(
\tqgis: AlgorithmHost,
\tid: K,
\tparams: AlgorithmRegistry[K]["params"],
\toptions?: HostInvokeOptions,
): Promise<AlgorithmRun<AlgorithmRegistry[K]["result"]>> {
\treturn runAny<AlgorithmRegistry, K>(qgis, id, params, options);
}"""


def _ts_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _ts_comment(text: str) -> str:
    return text.replace("*/", "* /").replace("\n", " ")


def render_package(
    catalogue: Catalogue, providers: Sequence[str] | None = None, *, init: bool = True
) -> dict[str, str]:
    """Every file of a generated Python package, by name relative to it.

    ``catalogue.json`` holds the catalogue restricted to ``providers`` (the
    fake and ``describe`` read it), one ``<provider>.py`` per provider, and
    ``__init__.py`` unless ``init`` is false (the runtime's own snapshot keeps
    a hand-written init next to the generated modules).
    """
    wanted = (
        tuple(providers)
        if providers is not None
        else tuple(p.id for p in catalogue.providers)
    )
    restricted = Catalogue(
        qgis_version=catalogue.qgis_version,
        providers=tuple(p for p in catalogue.providers if p.id in wanted),
        algorithms=tuple(a for a in catalogue.algorithms if a.provider in wanted),
    )
    files: dict[str, str] = {"catalogue.json": restricted.to_json()}
    for provider in wanted:
        files[f"{_module_name(provider)}.py"] = emit_python_module(restricted, provider)
    if init:
        files["__init__.py"] = emit_python_package_init(restricted, wanted)
    return files


def _module_name(provider: str) -> str:
    """``3d`` -> ``p3d``: a provider id that is not an identifier gets a prefix."""
    name = _NON_WORD.sub("_", provider).strip("_").lower() or "provider"
    if name[0].isdigit():
        name = f"p{name}"
    if keyword.iskeyword(name):
        name = f"{name}_"
    return name


module_name = _module_name
__all__.append("module_name")
__all__.append("render_package")

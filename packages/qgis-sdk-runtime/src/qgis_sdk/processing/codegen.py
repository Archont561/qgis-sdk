"""Emit typed Python and TypeScript modules from a Processing catalogue.

Pure: a :class:`~qgis_sdk.models.Catalogue` in, text out, no QGIS. The
generator CLI (``qgis-sdk processing generate``), the repository's snapshot
script and the tests all call these two functions, so the shipped snapshot
and a project's generated modules are the same code from the same emitter.

What is emitted per provider:

* **Python** (:func:`emit_python_module`): a ``TypedDict`` with the QGIS
  parameter names (``BufferParams``) and one with the output names
  (``BufferResult``), and a keyword-only frozen dataclass per algorithm
  (``Buffer``) deriving from :class:`~qgis_sdk.models.TypedRun`, whose
  fields are the parameters under Python names; plus ``REGISTRY`` mapping
  ids to request classes and ``ALGORITHM_IDS``.
* **TypeScript** (:func:`emit_typescript_module`): ``NativeBufferParams`` /
  ``NativeBufferResult`` interfaces per algorithm, an ``AlgorithmRegistry``
  interface keyed by id (what ``runAlgorithm`` is generic over) and
  ``ALGORITHM_IDS``.

Type mapping is by QGIS parameter kind. Kinds this table does not know fall
back to ``object`` / ``unknown`` rather than failing, so a third-party
provider with a custom parameter type still generates.
"""


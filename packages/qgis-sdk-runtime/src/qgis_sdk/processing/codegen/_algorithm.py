def python_registry_lines(classes: list[tuple[str, str]]) -> list[str]:
    """The REGISTRY mapping and ``__all__`` for the request classes."""
    lines: list[str] = []
    lines.append("#: Every request class of this provider by algorithm id.")
    lines.append("REGISTRY: dict[str, type[TypedRun]] = {")
    lines.extend(f"    {q(algorithm_id)}: {name}," for algorithm_id, name in classes)
    lines.append("}")
    lines.append("")
    lines.append("ALGORITHM_IDS: tuple[str, ...] = tuple(REGISTRY)")
    lines.append("")
    exported = ["ALGORITHM_IDS", "PROVIDER", "REGISTRY"]
    exported += sorted(
        {f"{n}{suffix}" for _, n in classes for suffix in ("", "Params", "Result")}
    )
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in exported)
    lines.extend(["]", ""])
    return lines


def python_registry_body(
    catalogue: Catalogue, provider: str
) -> tuple[str, list[tuple[str, str]]]:
    """The request classes, REGISTRY and ``__all__`` for one provider."""
    algorithms = catalogue.by_provider(provider)
    body: list[str] = [f"PROVIDER = {q(provider)}", ""]
    classes: list[tuple[str, str]] = []
    taken: set[str] = set()
    for algorithm in algorithms:
        name = class_name(algorithm, taken)
        taken.add(name)
        classes.append((algorithm.id, name))
        from ._python import python_algorithm

        body.extend(python_algorithm(algorithm, name))
    if not algorithms:
        body.append("")
    body.extend(python_registry_lines(classes))
    return "\n".join(body), classes


def python_docstring(catalogue: Catalogue, provider: str) -> list[str]:
    """The generated module's docstring, naming its provider and shape."""
    count = len(catalogue.by_provider(provider))
    return [
        f'"""{HEADER.format(version=catalogue.qgis_version)}',
        "",
        f"Provider ``{provider}``: {count} algorithms. Each algorithm has a",
        "``...Params`` TypedDict (the QGIS parameter names, for ``run(id, params)``),",
        "a ``...Result`` TypedDict (its output names) and a keyword-only request",
        "class deriving from ``TypedRun`` (``run(native.Buffer(input=...))``).",
        '"""',
        "",
    ]

def python_algorithm_tail1(**values):
    algorithm = values["algorithm"]
    lines = values["lines"]
    name = values["name"]
    lines.append("@dataclass(frozen=True, slots=True, kw_only=True)")
    lines.append(f"class {name}(TypedRun):")
    doc = [f"{algorithm.label} (``{algorithm.id}``)."]
    if algorithm.help:
        doc += ["", _first_sentence(algorithm.help)]
    fields: list[tuple[str, ParameterInfo]] = []
    used: list[str] = []
    for parameter in algorithm.parameters:
        field = field_name(parameter.name, used)
        used.append(field)
        fields.append((field, parameter))
    doc += ["", "Parameters:"]
    for field, parameter in fields:
        note = " (required)" if parameter.required else ""
        if parameter.destination:
            note = " (destination; allocated when left out)"
        label = parameter.label or parameter.name
        doc.append(f"    {field}: {label}{note}")
        if parameter.options:
            doc.append(f"        one of: {', '.join(parameter.options)}")
    if algorithm.outputs:
        doc += ["", "Outputs: " + ", ".join(o.name for o in algorithm.outputs)]
    lines.append(_docstring(doc, "    "))
    lines.append("")
    return _python_algorithm_facts11(algorithm, fields, lines)


def _python_algorithm_facts11(algorithm, fields, lines):
    algorithm_line = f"    algorithm: ClassVar[str] = {q(algorithm.id)}"
    if len(algorithm_line) > 88:
        algorithm_line = (
            f"    algorithm: ClassVar[str] = (\n        {q(algorithm.id)}\n    )"
        )
    lines.append(algorithm_line)
    return _python_algorithm_facts1(fields, lines)


def _python_algorithm_facts1(fields, lines):
    if fields:
        lines.append("    _names: ClassVar[dict[str, str]] = {")
        lines.extend(
            f"        {q(field)}: {q(parameter.name)}," for field, parameter in fields
        )
        lines.append("    }")
    else:
        lines.append("    _names: ClassVar[dict[str, str]] = {}")
    required = [(f, p) for f, p in fields if p.required]
    optional = [(f, p) for f, p in fields if not p.required]
    for field, parameter in required:
        lines.append(f"    {field}: {python_type(parameter)}")
    for field, parameter in optional:
        lines.append(f"    {field}: {python_type(parameter)} | None = None")
    lines.append("")
    lines.append("")
    return lines



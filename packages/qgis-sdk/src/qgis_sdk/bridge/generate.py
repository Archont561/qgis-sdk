"""Generate a typed TypeScript client from one plugin description.

The input is the object ``describe_plugin`` already produces
([decision-26](../../../../../backlog/decisions/decision-26%20-%20Derive-the-bridge-allowlist-and-the-generated-client-from-one-declared-manifest.md)):
the plugin's id, its actions, and the request/result schemas each action
declares. The output is one module with the value types, a nested operations
map, runtime validators and `createOperations(client)`, so a frontend never
hand-writes a contract or asserts a type at a call site.

Three rules make the output trustworthy:

* **Deterministic.** The same description always produces the same bytes -
  sorted actions, no timestamps, no environment - so a checked-in file can be
  diffed by CI and reviewed like any other source.
* **Closed subset.** The generator speaks exactly the schemas
  :mod:`qgis_sdk.declarations` emits. Anything else raises rather than emitting
  ``any``, because a type that promises nothing is worse than a build failure.
* **Asymmetric.** Input validators reject unknown properties, result validators
  tolerate them: a host may add a field without breaking an older frontend, but
  a misspelled argument never reaches Python (decision-22).

The generated module imports nothing from the SDK. A frontend passes its own
``BridgeClient`` (anything with an ``invoke`` method), which keeps the artifact
usable with a scripted transport in a test.
"""

from __future__ import annotations

import hashlib
import importlib
import json
import sys
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from qgis_sdk.models.errors import QgisSdkBridgeError
from qgis_sdk.models.limits import MAX_SAFE_INTEGER

GENERATED_MARKER = "// Generated by qgis-sdk. Do not edit."
_SIMPLE_TYPES = {
    "string": "string",
    "boolean": "boolean",
    "number": "number",
    "integer": "number",
    "null": "null",
}
_KNOWN_KEYWORDS = frozenset(
    {
        "type",
        "properties",
        "required",
        "additionalProperties",
        "items",
        "anyOf",
        "enum",
        "minimum",
        "maximum",
        "title",
        "description",
    }
)
_IDENTIFIER_SAFE = frozenset(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_$"
)


@dataclass(frozen=True, slots=True)
class _Surface:
    """The names one rendered module exports.

    Two surfaces share one renderer: a plugin module generated per plugin (each
    page imports one) and the host module shipped inside the npm package. Their
    identifiers differ so a page can import both without a collision.
    """

    operations_type: str
    factory: str
    id_const: str
    fingerprint_const: str
    version_const: str
    operations_const: str
    operation_id_type: str
    options_type: str
    client_type: str
    error_type: str
    header: tuple[str, ...]


PLUGIN_SURFACE = _Surface(
    operations_type="PluginOperations",
    factory="createOperations",
    id_const="PLUGIN_ID",
    fingerprint_const="CONTRACT_FINGERPRINT",
    version_const="PLUGIN_DESCRIPTION_SCHEMA_VERSION",
    operations_const="OPERATIONS",
    operation_id_type="OperationId",
    options_type="InvokeOptions",
    client_type="BridgeClientLike",
    error_type="ContractError",
    header=(
        "// Source: the declarations of {id}.",
        "// Regenerate with `qgis-sdk bridge generate`; CI fails when this file is stale.",
    ),
)

HOST_SURFACE = _Surface(
    operations_type="HostOperations",
    factory="createHost",
    id_const="HOST_ID",
    fingerprint_const="HOST_FINGERPRINT",
    version_const="HOST_SCHEMA_VERSION",
    operations_const="HOST_OPERATIONS",
    operation_id_type="HostOperationId",
    options_type="HostInvokeOptions",
    client_type="HostClientLike",
    error_type="HostContractError",
    header=(
        "// Source: the curated host manifest in qgis_sdk.bridge.host.",
        "// Regenerate with `qgis-sdk bridge generate --host`; CI fails on drift.",
    ),
)


def contract_fingerprint(description: Any) -> str:
    """Return the digest a client can compare against the host's declaration.

    Only what crosses the wire is hashed: the description version, the plugin id
    and each action's id, request and result. Titles and the Python handler name
    stay out, so renaming a method or rewording a label does not invalidate an
    already-generated client, while any change a frontend could observe does.
    """
    canonical = json.dumps(
        _contract_view(_as_mapping(description)),
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    )
    return "sha256:" + hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _contract_view(description: Mapping[str, Any]) -> dict[str, Any]:
    actions = [
        {"id": action["id"], "request": action["request"], "result": action["result"]}
        for action in sorted(description["actions"], key=lambda item: str(item["id"]))
    ]
    return {
        "schema_version": description.get("schema_version"),
        "id": description.get("id"),
        "actions": actions,
    }


def describe_plugin_spec(spec: str) -> dict[str, Any]:
    """Describe ``module:attribute``, importing it the way a plugin dev tree does.

    The working directory goes on ``sys.path`` first, so the command runs from the
    plugin's own root without an installed copy or an activated environment. The
    import is trusted author code: like ``describe_plugin``, this is a build step
    for the developer's own plugin, not a sandbox.
    """
    module_name, separator, attribute = spec.partition(":")
    if not separator or not module_name.strip() or not attribute.strip():
        raise QgisSdkBridgeError(
            f"--plugin expects module:attribute, got {spec!r} "
            "(for example my_plugin.bridge:SitesPlugin)"
        )
    root = str(Path.cwd())
    if root not in sys.path:
        sys.path.insert(0, root)
    try:
        module = importlib.import_module(module_name)
    except ImportError as error:
        raise QgisSdkBridgeError(f"cannot import {module_name!r}: {error}") from error
    target = module
    for part in attribute.split("."):
        target = getattr(target, part, None)
        if target is None:
            raise QgisSdkBridgeError(f"{module_name!r} has no attribute {attribute!r}")
    from qgis_sdk.declarations import QgisSdkDeclarationError, describe_plugin

    try:
        return describe_plugin(target).to_dict()
    except QgisSdkDeclarationError as error:
        raise QgisSdkBridgeError(str(error)) from error


def load_description(path: Path) -> dict[str, Any]:
    """Read a description a host shipped, so a frontend can build without Python."""
    try:
        described = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise QgisSdkBridgeError(f"cannot read {path}: {error}") from error
    except json.JSONDecodeError as error:
        raise QgisSdkBridgeError(f"{path} is not JSON: {error}") from error
    if not isinstance(described, Mapping):
        raise QgisSdkBridgeError(f"{path} must contain a plugin description object")
    return _as_mapping(described)


def generate_typescript(description: Any) -> str:
    """Render a plugin's module for ``description``."""
    described = _as_mapping(description)
    generator = _Generator(described)
    return generator.render()


def generate_host_typescript(description: Any = None) -> str:
    """Render the curated host module shipped inside the npm package."""
    if description is None:
        from qgis_sdk.bridge.host import host_description

        description = host_description()
    described = _as_mapping(description)
    return _Generator(described, surface=HOST_SURFACE).render()


def check_generated(
    path: Path, description: Any, *, generate: Any = generate_typescript
) -> str | None:
    """Return a message when ``path`` is not what ``description`` generates."""
    expected = generate(description)
    if not path.exists():
        return f"{path} does not exist; run the generator to create it"
    if path.read_text(encoding="utf-8") != expected:
        return (
            f"{path} is out of date; regenerate it from the plugin declarations "
            "and commit the result"
        )
    return None


def write_generated(
    path: Path, description: Any, *, generate: Any = generate_typescript
) -> bool:
    """Write the module, returning whether anything changed."""
    rendered = generate(description)
    if path.exists() and path.read_text(encoding="utf-8") == rendered:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered, encoding="utf-8")
    return True


def _declared_name(preferred: Any, fallback: str) -> str:
    """Use the manifest's name when it gave one, so a public type can be named."""
    if isinstance(preferred, str) and preferred.isidentifier():
        return preferred
    return fallback


def _as_mapping(description: Any) -> dict[str, Any]:
    if hasattr(description, "to_dict"):
        described = description.to_dict()
    elif isinstance(description, Mapping):
        described = dict(description)
    else:
        raise QgisSdkBridgeError(
            "description must be a PluginDescription or a mapping with actions"
        )
    if not isinstance(described.get("actions"), list):
        raise QgisSdkBridgeError("description.actions must be a list")
    for action in described["actions"]:
        if not isinstance(action, Mapping) or not isinstance(action.get("id"), str):
            raise QgisSdkBridgeError("every action needs an id")
    return described


@dataclass(frozen=True, slots=True)
class _Action:
    """One action, with the names its generated pieces are given."""

    id: str
    base: str
    request: Mapping[str, Any]
    result: Mapping[str, Any]
    takes_input: bool
    request_name: str | None = None
    result_name: str | None = None


class _Generator:
    """Collect the schema pieces, then render them in a fixed order."""

    def __init__(
        self, description: Mapping[str, Any], *, surface: _Surface = PLUGIN_SURFACE
    ) -> None:
        self._description = description
        self._surface = surface
        self._objects: list[tuple[str, Mapping[str, Any]]] = []
        self._names: dict[int, str] = {}
        self._actions = self._collect_actions()

    # -- collection ----------------------------------------------------

    def _collect_actions(self) -> tuple[_Action, ...]:
        actions: list[_Action] = []
        seen: set[str] = set()
        for raw in sorted(
            self._description["actions"], key=lambda item: str(item["id"])
        ):
            action_id = str(raw["id"])
            if action_id in seen:
                raise QgisSdkBridgeError(f"duplicate action id {action_id!r}")
            seen.add(action_id)
            request = raw.get("request")
            result = raw.get("result")
            if not isinstance(request, Mapping) or not isinstance(result, Mapping):
                raise QgisSdkBridgeError(
                    f"{action_id}: the generator needs declared request and result schemas"
                )
            base = _pascal(action_id)
            request_name = raw.get("request_name")
            result_name = raw.get("result_name")
            actions.append(
                _Action(
                    id=action_id,
                    base=base,
                    request=request,
                    result=result,
                    takes_input=bool(request.get("required")),
                    request_name=request_name
                    if isinstance(request_name, str)
                    else None,
                    result_name=result_name if isinstance(result_name, str) else None,
                )
            )
            self._declare(request, _declared_name(request_name, f"{base}Request"))
            self._declare(result, _declared_name(result_name, f"{base}Result"))
        return tuple(actions)

    def _declare(self, schema: Mapping[str, Any], name: str) -> str:
        """Name every object below ``schema`` before anything is rendered.

        Naming has to finish first: a parent's field type is the child's name, so
        rendering as we descend would point the parent at a name not yet chosen.
        """
        _check_supported(schema, path=name)
        self._register(schema, name)
        return name

    def _register(self, schema: Mapping[str, Any], name: str) -> None:
        if schema.get("type") == "object":
            if id(schema) in self._names:
                return
            if any(existing == name for existing, _ in self._objects):
                raise QgisSdkBridgeError(
                    f"{name}: two declarations would generate the same type name; "
                    "rename one of the actions"
                )
            self._names[id(schema)] = name
            self._objects.append((name, schema))
        for key, item in (schema.get("properties") or {}).items():
            self._register(item, f"{name}{_pascal(str(key))}")
        if isinstance(schema.get("items"), Mapping):
            self._register(schema["items"], f"{name}Item")
        for branch in schema.get("anyOf", []) or []:
            if branch.get("type") == "object":
                raise QgisSdkBridgeError(
                    f"{name}: an object inside a union has no generated type yet; "
                    "declare it as its own dataclass instead"
                )

    def name_for(self, schema: Mapping[str, Any]) -> str | None:
        """Return the registered name of an object schema, if it has one."""
        return self._names.get(id(schema))

    # -- rendering -----------------------------------------------------

    def render(self) -> str:
        described = self._description
        surface = self._surface
        lines = [
            GENERATED_MARKER,
            *(
                line.format(id=described.get("id", "unknown plugin"))
                for line in surface.header
            ),
            "",
            f'export const {surface.id_const} = "{described.get("id", "")}";',
            (
                f"export const {surface.fingerprint_const} = "
                f'"{contract_fingerprint(described)}";'
            ),
            (
                f"export const {surface.version_const} = "
                f"{int(described.get('schema_version', 1))};"
            ),
            "",
            "/** Every declared operation id, so a name can be checked, not guessed. */",
            f"export const {surface.operations_const} = [",
            *(f'\t"{action.id}",' for action in self._actions),
            "] as const;",
            "",
            (
                f"export type {surface.operation_id_type} = "
                f"(typeof {surface.operations_const})[number];"
            ),
            "",
            f"export interface {surface.options_type} {{",
            "\treadonly signal?: AbortSignal;",
            "}",
            "",
            "/** The client this module wraps: anything with a correlated invoke. */",
            f"export interface {surface.client_type} {{",
            "\tinvoke(",
            "\t\toperation: string,",
            "\t\tpayload?: Readonly<Record<string, unknown>>,",
            f"\t\toptions?: {surface.options_type},",
            "\t): Promise<unknown>;",
            "}",
            "",
            "/** An argument or a response that does not match its declared schema. */",
            f"export class {surface.error_type} extends Error {{",
            "\tpublic readonly operation: string;",
            "\tpublic constructor(operation: string, message: string) {",
            '\t\tsuper(`operation "${operation}": ${message}`);',
            f'\t\tthis.name = "{surface.error_type}";',
            "\t\tthis.operation = operation;",
            "\t}",
            "}",
            "",
            "function isRecord(value: unknown): value is Record<string, unknown> {",
            '\treturn typeof value === "object" && value !== null && !Array.isArray(value);',
            "}",
            "",
            "function hasOnly(",
            "\tvalue: Record<string, unknown>,",
            "\tkeys: readonly string[],",
            "): boolean {",
            "\treturn Object.keys(value).every((key) => keys.includes(key));",
            "}",
            "",
            "function isSafeInteger(value: unknown): value is number {",
            '\treturn typeof value === "number" && Number.isSafeInteger(value);',
            "}",
            "",
        ]
        for name, schema in sorted(self._objects):
            lines.extend(_interface_lines(schema, name, self))
            lines.append("")
        for name, schema in sorted(self._objects):
            lines.extend(_validator_lines(schema, name, self))
            lines.append("")
        lines.extend(self._render_operations())
        return "\n".join(lines).rstrip("\n") + "\n"

    def _render_operations(self) -> list[str]:
        surface = self._surface
        lines = [
            "/** Every operation this surface declares, as callable methods. */",
            f"export interface {surface.operations_type} {{",
        ]
        lines.extend(_tree_lines(self._actions, self._member_type))
        lines.extend(["}", ""])
        lines.extend(
            [
                (
                    f"export function {surface.factory}("
                    f"client: {surface.client_type}): {surface.operations_type} {{"
                ),
                "\treturn {",
            ]
        )
        lines.extend(_tree_body_lines(self._actions, self._member_body))
        lines.extend(["\t};", "}", ""])
        lines.append(_call_helper(surface).rstrip("\n"))
        lines.append("")
        return lines

    def _member_type(self, action: _Action) -> str:
        input_name = self._type_name(action.request, f"{action.base}Request")
        output_name = self._type_name(action.result, f"{action.base}Result")
        optional = "" if action.takes_input else "?"
        tail = _quote(action.id.rsplit(".", 1)[-1])
        return (
            f"readonly {tail}: (input{optional}: {input_name}, "
            f"options?: {self._surface.options_type}) => Promise<{output_name}>;"
        )

    def _member_body(self, action: _Action) -> str:
        input_name = self._type_name(action.request, f"{action.base}Request")
        output_name = self._type_name(action.result, f"{action.base}Result")
        tail = action.id.rsplit(".", 1)[-1]
        accepts_input = self._accepts(action.request)
        accepts_output = self._accepts(action.result)
        optional = "" if action.takes_input else "?"
        return (
            f"{_quote(tail)}: (input{optional}: {input_name}, "
            f"options?: {self._surface.options_type}) =>\n"
            f"\t\t\t\tcall<{output_name}>(\n"
            f'\t\t\t\t\tclient, "{action.id}", input, options,\n'
            f"\t\t\t\t\t{accepts_input},\n"
            f"\t\t\t\t\t{accepts_output},\n"
            f"\t\t\t\t),"
        )

    def _type_name(self, schema: Mapping[str, Any], fallback: str) -> str:
        return self.name_for(schema) or _inline_type(schema)

    def _accepts(self, schema: Mapping[str, Any]) -> str:
        """Return the predicate ``call`` should use for this value.

        A named object schema becomes its generated validator; anything else
        (``null``, a bare string, an enum) becomes an inline predicate, wrapped in
        a lambda because ``call`` takes a function either way.
        """
        name = self.name_for(schema)
        if name is not None:
            return name
        predicate = _inline_validator(schema, "candidate")
        return f"(candidate: unknown) => {predicate}"


_CALL_HELPER = """async function call<T>(
\tclient: BridgeClientLike,
\toperation: string,
\tinput: unknown,
\toptions: InvokeOptions | undefined,
\tacceptInput: (value: unknown, strict?: boolean) => boolean,
\tacceptOutput: (value: unknown) => boolean,
): Promise<T> {
\tif (input !== undefined && !acceptInput(input, true)) {
\t\tthrow new ContractError(operation, "the arguments do not match the declared request");
\t}
\tconst value = await client.invoke(
\t\toperation,
\t\t(input ?? {}) as Readonly<Record<string, unknown>>,
\t\toptions,
\t);
\tif (!acceptOutput(value)) {
\t\tthrow new ContractError(operation, "the response does not match the declared result");
\t}
\treturn value as T;
}
"""


def _call_helper(surface: _Surface) -> str:
    """Render the call helper with this surface's identifiers."""
    helper = _CALL_HELPER
    for placeholder, name in (
        ("BridgeClientLike", surface.client_type),
        ("InvokeOptions", surface.options_type),
        ("ContractError", surface.error_type),
    ):
        helper = helper.replace(placeholder, name)
    return helper


def _tree_lines(actions: tuple[_Action, ...], render: Any) -> list[str]:
    """Render the nested interface, grouping ids by their leading segments."""
    tree = _group(actions)
    return _emit_tree(tree, render, depth=1)


def _tree_body_lines(actions: tuple[_Action, ...], render: Any) -> list[str]:
    tree = _group(actions)
    return _emit_tree_body(tree, render, depth=2)


def _group(actions: tuple[_Action, ...]) -> dict[str, Any]:
    root: dict[str, Any] = {}
    for action in actions:
        segments = action.id.split(".")
        node = root
        for segment in segments[:-1]:
            node = node.setdefault(segment, {})
            if not isinstance(node, dict):
                raise QgisSdkBridgeError(
                    f"{action.id}: conflicts with an action of the same prefix"
                )
        if segments[-1] in node and isinstance(node[segments[-1]], dict):
            raise QgisSdkBridgeError(
                f"{action.id}: conflicts with actions declared below it"
            )
        node[segments[-1]] = action
    return root


def _emit_tree(tree: dict[str, Any], render: Any, *, depth: int) -> list[str]:
    lines: list[str] = []
    indent = "\t" * depth
    for key in sorted(tree):
        value = tree[key]
        if isinstance(value, dict):
            lines.append(f"{indent}readonly {_quote(key)}: {{")
            lines.extend(_emit_tree(value, render, depth=depth + 1))
            lines.append(f"{indent}}};")
        else:
            lines.append(f"{indent}{render(value)}")
    return lines


def _emit_tree_body(tree: dict[str, Any], render: Any, *, depth: int) -> list[str]:
    lines: list[str] = []
    indent = "\t" * depth
    for key in sorted(tree):
        value = tree[key]
        if isinstance(value, dict):
            lines.append(f"{indent}{_quote(key)}: {{")
            lines.extend(_emit_tree_body(value, render, depth=depth + 1))
            lines.append(f"{indent}}},")
        else:
            lines.append(f"{indent}{render(value)}")
    return lines


def _interface_lines(
    schema: Mapping[str, Any], name: str, generator: _Generator
) -> list[str]:
    required = set(schema.get("required", []) or [])
    properties: Mapping[str, Any] = schema.get("properties") or {}
    lines = [f"export interface {name} {{"]
    for key in sorted(properties):
        optional = "" if key in required else "?"
        lines.append(
            f"\treadonly {_quote(str(key))}{optional}: "
            f"{_field_type(properties[key], generator)};"
        )
    if not properties:
        lines.append("\treadonly [key: string]: never;")
    lines.append("}")
    return lines


def _validator_lines(
    schema: Mapping[str, Any], name: str, generator: _Generator
) -> list[str]:
    required = list(schema.get("required", []) or [])
    properties: Mapping[str, Any] = schema.get("properties") or {}
    lines = [
        f"export function {name}(value: unknown, strict = false): value is {name} {{",
        "\tif (!isRecord(value)) return false;",
    ]
    for key in required:
        lines.append(f'\tif (!("{key}" in value)) return false;')
    for key in sorted(properties):
        expression = _member_validator(
            f"value[{json.dumps(str(key))}]", properties[key], generator
        )
        lines.append(
            f"\tif (value[{json.dumps(str(key))}] !== undefined && !({expression})) {{"
        )
        lines.append("\t\treturn false;")
        lines.append("\t}")
    known = ", ".join(json.dumps(str(key)) for key in sorted(properties))
    lines.append(f"\tif (strict && !hasOnly(value, [{known}])) return false;")
    lines.append("\treturn true;")
    lines.append("}")
    return lines


def _field_type(schema: Mapping[str, Any], generator: _Generator) -> str:
    """Name an object by its registered interface, and look inside an array."""
    name = generator.name_for(schema)
    if name is not None:
        return name
    if schema.get("type") == "array":
        return f"readonly {_field_type(schema['items'], generator)}[]"
    return _inline_type(schema)


def _member_validator(
    expression: str, schema: Mapping[str, Any], generator: _Generator
) -> str:
    """Validate by name where the item has one, so a page item uses its interface."""
    name = generator.name_for(schema)
    if name is not None:
        return f"{name}({expression}, strict)"
    if schema.get("type") == "array":
        inner = _member_validator("item", schema["items"], generator)
        return f"(Array.isArray({expression}) && {expression}.every((item) => {inner}))"
    return _inline_validator(schema, expression)


def _inline_type(schema: Mapping[str, Any]) -> str:
    if "anyOf" in schema:
        return " | ".join(_inline_type(branch) for branch in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(_literal(value) for value in schema["enum"])
    declared = schema.get("type")
    if declared == "array":
        return f"readonly {_inline_type(schema['items'])}[]"
    if declared in _SIMPLE_TYPES:
        return _SIMPLE_TYPES[declared]
    if declared == "object":
        return "Record<string, unknown>"
    raise QgisSdkBridgeError(f"cannot render a type for {declared!r}")


def _inline_validator(schema: Mapping[str, Any], expression: str) -> str:
    if "anyOf" in schema:
        return (
            "("
            + " || ".join(
                _inline_validator(branch, expression) for branch in schema["anyOf"]
            )
            + ")"
        )
    if "enum" in schema:
        return (
            "("
            + " || ".join(
                f"{expression} === {_literal(value)}" for value in schema["enum"]
            )
            + ")"
        )
    declared = schema.get("type")
    if declared == "array":
        return (
            f"(Array.isArray({expression}) && {expression}.every((item) => "
            f"{_inline_validator(schema['items'], 'item')}))"
        )
    if declared == "string":
        return f'typeof {expression} === "string"'
    if declared == "boolean":
        return f'typeof {expression} === "boolean"'
    if declared == "number":
        return f'typeof {expression} === "number" && Number.isFinite({expression})'
    if declared == "integer":
        # The safe range is already `isSafeInteger`; a tighter bound the manifest
        # declared (a page size, say) is worth refusing before the transport,
        # because the host would refuse it anyway and the page could have known.
        checks = [f"isSafeInteger({expression})"]
        for keyword, operator in (("minimum", ">="), ("maximum", "<=")):
            bound = schema.get(keyword)
            if isinstance(bound, int) and abs(bound) != MAX_SAFE_INTEGER:
                checks.append(f"{expression} {operator} {bound}")
        if len(checks) == 1:
            return checks[0]
        return "(" + " && ".join(checks) + ")"
    if declared == "null":
        return f"{expression} === null"
    if declared == "object":
        return f"isRecord({expression})"
    raise QgisSdkBridgeError(f"cannot validate {declared!r}")


def _check_supported(schema: Any, *, path: str) -> None:
    if not isinstance(schema, Mapping):
        raise QgisSdkBridgeError(f"{path}: a schema must be an object")
    unknown = set(schema) - _KNOWN_KEYWORDS
    if unknown:
        raise QgisSdkBridgeError(
            f"{path}: unsupported schema keyword(s) {', '.join(sorted(unknown))}"
        )
    for key, item in (schema.get("properties") or {}).items():
        _check_supported(item, path=f"{path}.{key}")
    if isinstance(schema.get("items"), Mapping):
        _check_supported(schema["items"], path=f"{path}[]")
    for branch in schema.get("anyOf", []) or []:
        _check_supported(branch, path=path)


def _pascal(value: str) -> str:
    parts = [part for part in value.replace("-", ".").split(".") if part]
    name = "".join(part[:1].upper() + part[1:] for part in parts)
    if not name:
        raise QgisSdkBridgeError(f"cannot name a type for {value!r}")
    return name if name[0].isalpha() else f"Op{name}"


def _quote(value: str) -> str:
    if (
        value
        and all(character in _IDENTIFIER_SAFE for character in value)
        and not value[0].isdigit()
    ):
        return value
    return json.dumps(value)


def _literal(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return json.dumps(value)


